#!/usr/bin/env python3
"""Build diagnostic init_boot probes on the host; never invoke adb/fastboot.

Probe kinds:
  reboot-bootloader  /init is a tiny hand-assembled static AArch64 ELF that sleeps
                     5 s and calls reboot(RESTART2, "bootloader"). Landing in
                     fastboot by itself proves kernel start + our PID 1 execution.
  original-ramdisk   the pinned original ramdisk bytes with an AVB footer
                     regenerated by our pipeline (isolates footer/verification).
"""
import argparse
import gzip
import io
import json
from pathlib import Path
import shutil
import stat
import struct
import subprocess
import tempfile

import build_candidate as cand
import build_initramfs as ramfs
import inspect_boot

ROOT = Path(__file__).resolve().parents[1]
BASE = 0x400000


def movz(rd, imm, hw=0):
    return 0xD2800000 | hw << 21 | imm << 5 | rd


def movk(rd, imm, hw):
    return 0xF2800000 | hw << 21 | imm << 5 | rd


def adr(rd, offset):
    return 0x10000000 | (offset & 3) << 29 | ((offset >> 2) & 0x7FFFF) << 5 | rd


SVC0 = 0xD4000001


def reboot_init(target=b"bootloader", delay=5):
    """Static ELF: nanosleep(delay); reboot(MAGIC1, MAGIC2, RESTART2, target); block forever."""
    code = [
        adr(0, 0), movz(1, 0), movz(8, 101), SVC0,               # nanosleep(&ts, NULL); x0 patched below
        movz(0, 0xDEAD), movk(0, 0xFEE1, 1),
        movz(1, 0x1969), movk(1, 0x2812, 1),
        movz(2, 0xC3D4), movk(2, 0xA1B2, 1),
        adr(3, 0), movz(8, 142), SVC0,                           # reboot; x3 patched below
        movz(0, 0), movz(1, 0), movz(2, 0), movz(3, 0), movz(8, 73), SVC0,  # ppoll(NULL,0,NULL,NULL)
        0x17FFFFFA,                                              # b back to ppoll setup
    ]
    text_len = len(code) * 4
    ts_off = text_len                       # struct timespec {delay, 0}, 8-byte aligned
    arg_off = ts_off + 16
    code[0] = adr(0, ts_off - 0)
    code[10] = adr(3, arg_off - 40)
    body = b"".join(struct.pack("<I", x) for x in code) + struct.pack("<qq", delay, 0) + target + b"\0"
    header_size = 64 + 56
    entry = BASE + header_size
    total = header_size + len(body)
    ehdr = (b"\x7fELF\x02\x01\x01" + b"\0" * 9
            + struct.pack("<HHIQQQIHHHHHH", 2, 183, 1, entry, 64, 0, 0, 64, 56, 1, 64, 0, 0))
    phdr = struct.pack("<IIQQQQQQ", 1, 5, 0, BASE, BASE, total, total, 0x1000)
    return ehdr + phdr + body


def lz4_legacy(cpio, lz4):
    # Same container as the original generic ramdisk; the kernel concatenation
    # with the LZ4-legacy vendor ramdisk is suspected to reject a gzip member.
    return subprocess.run([lz4, "-l", "-12", "-c"], input=cpio, stdout=subprocess.PIPE, check=True).stdout


def probe_ramdisk(kind, originals, lz4, compression="gzip"):
    if kind == "original-ramdisk":
        layout = inspect_boot.inspect(originals["init_boot.img"])
        start, size = layout["ramdisk"]["offset"], layout["ramdisk"]["size"]
        return None, originals["init_boot.img"][start:start + size]
    init = reboot_init()
    entries = [(n, stat.S_IFDIR | 0o755, b"", 0, 0) for n in ("dev", "proc", "sys")]
    entries += [("init", stat.S_IFREG | 0o755, init, 0, 0)]
    entries += [(f"dev/{n}", stat.S_IFCHR | 0o600, b"", ma, mi)
                for n, ma, mi in (("console", 5, 1), ("null", 1, 3), ("kmsg", 1, 11))]
    cpio = ramfs.newc(entries)
    if compression == "lz4":
        return cpio, lz4_legacy(cpio, lz4)
    out = io.BytesIO()
    with gzip.GzipFile(filename="", mode="wb", fileobj=out, mtime=0, compresslevel=9) as f:
        f.write(cpio)
    return cpio, out.getvalue()


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("kind", choices=["reboot-bootloader", "original-ramdisk"])
    parser.add_argument("--compression", choices=["gzip", "lz4"], default="gzip")
    parser.add_argument("--ota-dir", type=Path, default=ROOT / "build" / "ota")
    parser.add_argument("--output", type=Path, default=ROOT / "build" / "probe")
    args = parser.parse_args()
    output = args.output.resolve()
    if not output.is_relative_to((ROOT / "build").resolve()) or output == (ROOT / "build" / "ota").resolve():
        raise ValueError("Probe outputs must stay in build/ and away from originals")
    originals = {}
    for name, expected in cand.ORIGINAL_HASHES.items():
        originals[name] = (args.ota_dir / name).read_bytes()
        if cand.digest(originals[name]) != expected:
            raise ValueError(f"Original {name} hash mismatch")
    avbtool, lz4 = shutil.which("avbtool"), shutil.which("lz4")
    cpio, compressed = probe_ramdisk(args.kind, originals, lz4, args.compression)
    raw = cand.unsigned_image(originals["init_boot.img"], compressed)
    output.mkdir(parents=True, exist_ok=True)
    props = dict(cand.AVB_PROPERTIES, **{"org.rodin.experiment": "probe-" + args.kind + "-" + args.compression})
    with tempfile.TemporaryDirectory(dir=output) as work:
        image = Path(work) / "init_boot.img"
        image.write_bytes(raw)
        command = [avbtool, "add_hash_footer", "--image", str(image), "--partition_size",
                   str(len(originals["init_boot.img"])), "--partition_name", "init_boot",
                   "--algorithm", "NONE", "--hash_algorithm", "sha256", "--salt", cand.AVB_SALT]
        for name, value in props.items():
            command += ["--prop", name + ":" + value]
        subprocess.run(command, check=True)
        subprocess.run([avbtool, "verify_image", "--image", str(image)], check=True)
        data = image.read_bytes()
    name = f"init_boot-probe-{args.kind}-{args.compression}.img"
    (output / name).write_bytes(data)
    if cpio is not None:
        (output / f"init-{args.kind}.elf").write_bytes(reboot_init())
    print(json.dumps({"image": str(output / name), "sha256": cand.digest(data), "size": len(data),
                      "ramdisk_sha256": cand.digest(compressed)}, indent=2))


if __name__ == "__main__":
    main()
